// CryptRadar's model: one sealed snapshot of the protocol universe in, one ranked board out.
//
// What a launch would be worth, from the snapshot's own figures only:
//
//   implied = TVL x categoryMultiple x growthMult x maturityMult x chainMult
//
//   categoryMultiple  what a token in this line of business is worth relative to the
//                     value locked in it. RWA pays 0.35 (its yield assets already
//                     price like securities), lending / CDP / collateral and trading
//                     (Dexs, derivatives, basis trading) pay 0.30, yield and the
//                     curator / allocator vaults pay 0.28, everything else pays 0.25,
//                     and the thin-margin lines (restaking, staking pools, chains,
//                     payments, bridges, insurance, governance incentives) pay 0.22.
//                     The category is one of the snapshot's own ten fields, so the
//                     multiple follows from the record, never from a name.
//   growthMult        1 + clamp(change_7d, -60, 120) / 100 x 0.5. A protocol gaining
//                     value locked is worth more than one losing it; the clamp keeps
//                     one wild week from deciding the board.
//   maturityMult      0.6 + min(age_days, 1095) / 1095 x 0.4. A protocol that has run
//                     for years with no token recorded has had years to build the
//                     user base a launch would pay out to. Age unknown: 365 days.
//   chainMult         1 + 0.02 x min(chains - 1, 5). A protocol live on more chains
//                     reaches more users; capped at +10% so breadth never beats size.
//
// No protocol name is ever special-cased: the same function scores every row.
// A protocol is pre-token when its record carries no token (no market cap, no
// CoinGecko id, no symbol). The board says a protocol "records no token", never
// that it has none: the snapshot's record is not proof.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and adds the 160 pre-token protocols below the floor with the most
// TVL: the early rows the radar exists to find. Live-token protocols are kept
// apart and shown with the market's own values, never mixed into the ranking.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

